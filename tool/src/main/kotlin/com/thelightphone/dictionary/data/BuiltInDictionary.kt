    private val entryMap: Map<String, WordEntry> by lazy {
        entries.associateBy { it.word.lowercase() }
    }

    fun find(word: String): WordEntry? {
        return entryMap[word.trim().lowercase()]
    }

    fun search(query: String): List<String> {
        val q = query.trim().lowercase()
        if (q.isBlank()) return emptyList()
        return entries
            .map { it.word }
            .filter { it.contains(q) }
            .sortedWith(
                compareBy<String> { !it.startsWith(q) }
                    .thenBy { it.length }
                    .thenBy { it }
            )
    }

    fun getAlphabeticalIndex(): List<String> {
        return entries.map { it.word }
    }
